#!/usr/bin/env python3
"""Write firmware/include/panel_logo.h: the Surrklank mark as a 1-bit OLED bitmap.

Usage: python3 -I firmware/tools/gen_panel_logo.py
The mark is the one on the PCB silkscreen: a square frame with the beamed-notes
glyph at 55 % of the frame height. The glyph path is read from
hardware/tools/gen_logo_footprints.py, so the board and the screen share one
source. Pixels are set where at least half of a 4 x 4 supersample lies inside.
"""
import importlib.util
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SIZE = 40      # pixels, square
STROKE = 3     # frame width in pixels (0.7 mm of 10 mm is about 2.8)
SAMPLES = 4


def load_mark():
    spec = importlib.util.spec_from_file_location("mark", ROOT / "hardware/tools/gen_logo_footprints.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def inside(polygon, x, y):
    result = False
    for (x1, y1), (x2, y2) in zip(polygon, polygon[1:] + polygon[:1]):
        if (y1 > y) != (y2 > y) and x < x1 + (y - y1) * (x2 - x1) / (y2 - y1):
            result = not result
    return result


def bitmap():
    mark = load_mark()
    points = [tuple(float(v) for v in pair.split()) for pair in mark.NOTE_PATH.strip("MZ").split("L")]
    scale = SIZE * mark.RATIO / mark.NOTE_H
    note = [((x - mark.NOTE_W / 2) * scale + SIZE / 2, (y - mark.NOTE_H / 2) * scale + SIZE / 2) for x, y in points]
    rows = []
    for row in range(SIZE):
        bits = []
        for column in range(SIZE):
            frame = min(row, column, SIZE - 1 - row, SIZE - 1 - column) < STROKE
            hits = sum(inside(note, column + (i + 0.5) / SAMPLES, row + (j + 0.5) / SAMPLES)
                       for i in range(SAMPLES) for j in range(SAMPLES))
            bits.append(frame or hits * 2 >= SAMPLES * SAMPLES)
        rows.append(bits)
    return rows


def main():
    rows = bitmap()
    lines = []
    for bits in rows:
        data = [sum(1 << (7 - k) for k in range(8) if bits[byte * 8 + k]) for byte in range(SIZE // 8)]
        lines.append("    {" + ", ".join(f"0x{value:02x}" for value in data) + "},")
    text = (
        "#pragma once\n#include <stdint.h>\n\n"
        "// Generated by firmware/tools/gen_panel_logo.py from the PCB silkscreen mark.\n"
        "// Rows top to bottom, most significant bit leftmost.\n"
        f"constexpr int panel_logo_size = {SIZE};\n"
        f"constexpr uint8_t panel_logo[{SIZE}][{SIZE // 8}] = {{\n" + "\n".join(lines) + "\n};\n"
    )
    (ROOT / "firmware/include/panel_logo.h").write_text(text)
    print("\n".join("".join("#" if b else "." for b in bits) for bits in rows))


if __name__ == "__main__":
    main()
