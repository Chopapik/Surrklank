#!/usr/bin/env python3
"""Generate the LSM/HDD module schematic (four DRV8833 module slots).

Usage: python3 -I gen_lsm_hdd_module.py <output.kicad_sch>
The register bit order defined here is the reference for firmware migration
and is recorded in docs/WIRING.md.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from kicad_sch_lib import Sheet  # noqa: E402
import module_common as mc  # noqa: E402

FP_TERM = "TerminalBlock_Phoenix:TerminalBlock_Phoenix_PT-1,5-4-3.5-H_1x04_P3.50mm_Horizontal"
FP_BULK = "Capacitor_SMD:CP_Elec_10x10"
SLOT_OUTPUTS = ["IN1", "IN2", "IN3", "IN4", "EEP"]   # 595 outputs per DRV8833 slot
DRV_PIN = {"EEP": "1", "OUT1": "2", "OUT2": "3", "OUT3": "4", "OUT4": "5", "ULT": "6",
           "IN1": "7", "IN2": "8", "VCC": "9", "GND": "10", "IN3": "11", "IN4": "12"}


def net(m, sig):
    return f"M{m}_{sig}"


def outputs():
    """24 595 outputs in chain order U2, U3, U4 (QA..QH); last four unused."""
    seq = [net(m, s) for m in range(1, 5) for s in SLOT_OUTPUTS] + [None] * 4
    return seq[0:8], seq[8:16], seq[16:24]


def build(path):
    sh = Sheet("surrklank-lsm-hdd-module", "Surrklank LSM/HDD module (4 x DRV8833)", "0.1",
               comments=("Planned design, not built or tested. Wiring rules: docs/WIRING.md",
                         "Generated by hardware/tools/gen_lsm_hdd_module.py - do not edit by hand"))
    mc.ribbon_and_buffer(sh)

    o2, o3, o4 = outputs()
    mc.register(sh, "U2", 200.66, 50.8, "B_DATA", "SR1", o2)
    mc.register(sh, "U3", 200.66, 111.76, "SR1", "SR2", o3)
    mc.register(sh, "U4", 200.66, 172.72, "SR2", "SR_LAST", o4)
    mc.input_register(sh, "U5", 200.66, 241.3, [net(m, "ULT") for m in range(1, 5)] + ["GND"] * 4)

    # DRV8833 slots and motor terminals
    for m in range(1, 5):
        y = 45.72 + (m - 1) * 58.42
        drv = sh.symbol("surrklank:DRV8833_Module", f"M{m}", "DRV8833_Module", 292.1, y,
                        footprint="surrklank:DRV8833_Module_2x6_W15.24mm")
        for sig in ("IN1", "IN2", "IN3", "IN4", "EEP", "ULT", "OUT1", "OUT2", "OUT3", "OUT4"):
            sh.connect(drv, DRV_PIN[sig], net(m, sig))
        sh.connect(drv, DRV_PIN["VCC"], "+5V")
        sh.connect(drv, DRV_PIN["GND"], "GND")
        term = sh.symbol("Connector:Screw_Terminal_01x04", f"J{5 + m}", f"MOTOR_M{m}", 342.9, y,
                         footprint=FP_TERM)
        for i in range(4):
            sh.connect(term, str(i + 1), net(m, f"OUT{i + 1}"))
    sh.text("Bridge A: OUT1/OUT2 (LSM coil A or one HDD VCM).\n"
            "Bridge B: OUT3/OUT4 (LSM coil B or a second HDD VCM).\n"
            "Never join outputs of different bridges or tie a coil to GND/+5V.",
            (236.22, 15.24))

    # EEP pull-downs (asleep at power-up when J1 on the module is open), ULT pull-ups
    mc.pack(sh, "RN10", "100k", 241.3, 198.12, [net(m, "EEP") for m in range(1, 5)], rail="GND")
    mc.pack(sh, "RN11", "10k", 256.54, 198.12, [net(m, "ULT") for m in range(1, 5)], rail="+3V3")

    # Power: Molex (second one optional), bulk capacitor, LDO for logic
    mc.molex(sh, "J5", 45.72, 203.2)
    j10 = sh.symbol("Connector_Generic:Conn_01x04", "J10", "MOLEX_5V_OPT", 45.72, 233.68,
                    footprint=mc.FP_MOLEX, dnp=True)
    sh.no_connect(j10, "1")
    sh.connect(j10, "2", "GND")
    sh.connect(j10, "3", "GND")
    sh.connect(j10, "4", "+5V")
    sh.text("J5/J10 pin 1 (+12V, yellow) is not connected; pin 4 must carry +5V (red).\n"
            "J10 is fitted only if measured motor current needs it.", (25.4, 248.92))
    bulk = sh.symbol("Device:C_Polarized", "C8", "470u 16V", 76.2, 266.7, footprint=FP_BULK)
    sh.connect(bulk, "1", "+5V")
    sh.connect(bulk, "2", "GND")
    mc.ldo(sh, 104.14, 198.12)
    sh.flag("+5V", (88.9, 233.68))
    sh.flag("GND", (101.6, 241.3))

    mc.decoupling(sh, 5, 134.62, 266.7)
    mc.mounting_holes(sh, 236.22, 279.4)
    sh.save(path)


if __name__ == "__main__":
    build(sys.argv[1])
