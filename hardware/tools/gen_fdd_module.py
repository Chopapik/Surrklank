#!/usr/bin/env python3
"""Generate the FDD module schematic (four floppy drives) from WIRING.md rules.

Usage: python3 -I gen_fdd_module.py <output.kicad_sch>
The register bit order defined here is the reference for firmware migration
and is recorded in docs/WIRING.md.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from kicad_sch_lib import Sheet  # noqa: E402
import module_common as mc  # noqa: E402

FP_SOIC16 = "Package_SO:SOIC-16_3.9x9.9mm_P1.27mm"
FP_SOIC20W = "Package_SO:SOIC-20W_7.5x12.8mm_P1.27mm"
FP_R = "Resistor_SMD:R_0805_2012Metric"
FP_C = "Capacitor_SMD:C_0805_2012Metric"
FP_C1206 = "Capacitor_SMD:C_1206_3216Metric"
FP_RN = "Resistor_SMD:R_Array_Convex_4x0603"
FP_IDC16 = "Connector_IDC:IDC-Header_2x08_P2.54mm_Vertical"
FP_IDE40 = "Connector_IDC:IDC-Header_2x20_P2.54mm_Vertical"
FP_HOLE = "MountingHole:MountingHole_3.2mm_M3"

DRIVE_OUTPUTS = ["DS0", "DS1", "DS2", "MOTOR", "DIR", "STEP"]   # 595 outputs per drive
DRIVE_PULLUPS = DRIVE_OUTPUTS + ["WD", "WG"]                      # never-floating drive inputs
FDD_PIN = {"DS0": 10, "DS1": 12, "DS2": 14, "MOTOR": 16, "DIR": 18, "STEP": 20,
           "WD": 22, "WG": 24, "TRK0": 26, "WP": 28}
QPINS = ["15", "1", "2", "3", "4", "5", "6", "7"]                 # 595 QA..QH
D165 = ["11", "12", "13", "14", "3", "4", "5", "6"]               # 165 D0..D7

# Ribbon (IN and OUT identical): pin -> signal; even pins are GND.
RIBBON = {1: "DATA", 3: "CLK", 5: "LATCH", 7: "OE", 9: "PL", 11: "CLK165", 13: "Q165", 15: "SPARE"}


def net(d, sig):
    return f"D{d}_{sig}"


def register_map():
    """24 595 outputs in chain order: U2 QA..QH, U3 QA..QH, U4 QA..QH."""
    seq = [net(d, s) for d in range(1, 5) for s in DRIVE_OUTPUTS]
    return {("U2", "U3", "U4")[i // 8] + "." + QPINS[i % 8]: n for i, n in enumerate(seq)}


def input_map():
    seq = [net(d, s) for d in range(1, 5) for s in ("TRK0", "WP")]
    return {D165[i]: n for i, n in enumerate(seq)}


def ide_pin(slot, fdd_pin):
    """IDE header pin for FDD pin of the first (slot 0) or second (slot 1) drive."""
    return fdd_pin - 9 if slot == 0 else fdd_pin + 11


def pack(sh, ref, value, x, y, bottom, top=None, rail=None):
    """R_Pack04: bottom pins 1-4 get nets; top pins 8-5 go to a rail or own nets."""
    rn = sh.symbol("Device:R_Pack04", ref, value, x, y, footprint=FP_RN)
    for k in range(4):
        b, t = str(k + 1), str(8 - k)
        if bottom[k] is None:
            sh.no_connect(rn, b)
            if rail is None:
                sh.no_connect(rn, t)
            continue
        sh.connect(rn, b, bottom[k])
        if rail is None:
            sh.connect(rn, t, top[k])
    if rail is not None:
        tops = [rn.pin(str(8 - k))["pos"] for k in range(4)]
        for a, b in zip(tops, tops[1:]):
            sh.wire(a, b)
        sh.connect(rn, "8", rail)
    return rn


def build(path):
    sh = Sheet("surrklank-fdd-module", "Surrklank FDD module (4 drives)", "0.1",
               comments=("Planned design, not built or tested. Wiring rules: docs/WIRING.md",
                         "Generated by hardware/tools/gen_fdd_module.py - do not edit by hand"))

    # Ribbon IN / OUT
    for ref, x, y, side in (("J1", 38.1, 50.8, "IN"), ("J2", 38.1, 101.6, "OUT")):
        j = sh.symbol("Connector_Generic:Conn_02x08_Odd_Even", ref, f"RIBBON_{side}", x, y,
                      footprint=FP_IDC16)
        for p in range(1, 17):
            if p % 2 == 0:
                sh.connect(j, str(p), "GND")
            elif RIBBON[p] == "SPARE":
                sh.connect(j, str(p), "RIB_SPARE")   # unused wire, passes IN -> OUT
            elif RIBBON[p] == "Q165":
                sh.connect(j, str(p), "Q165" if side == "IN" else "Q165_NEXT")
            else:
                sh.connect(j, str(p), f"{side}_{RIBBON[p]}")
    sh.text("Ribbon pin 15 is a spare wire: IN and OUT are joined, nothing else.\n"
            "No power runs on the ribbon.", (25.4, 148.59))

    # Input buffer: IN_x -> B_x
    u1 = sh.symbol("74xx:74AHC244", "U1", "74LVC244A", 111.76, 63.5, footprint=FP_SOIC20W)
    chans = [("2", "18", "DATA"), ("4", "16", "CLK"), ("6", "14", "LATCH"), ("8", "12", "OE"),
             ("17", "3", "PL"), ("15", "5", "CLK165")]
    for a, y_, s in chans:
        sh.connect(u1, a, f"IN_{s}")
        sh.connect(u1, y_, f"B_{s}")
    for a, y_ in (("13", "7"), ("11", "9")):
        sh.connect(u1, a, "GND")
        sh.no_connect(u1, y_)
    for oe in ("1", "19"):
        sh.connect(u1, oe, "GND")
    sh.connect(u1, "20", "+3V3")
    sh.connect(u1, "10", "GND")

    # Default levels on the ribbon inputs and the chained 165 serial input
    pack(sh, "RN1", "10k", 96.52, 116.84, ["IN_DATA", "IN_CLK", "IN_LATCH", "IN_CLK165"], rail="GND")
    pack(sh, "RN2", "10k", 127.0, 116.84, ["IN_OE", "IN_PL", "Q165_NEXT", None], rail="+3V3")
    # Series resistors toward the OUT ribbon and back to the mainboard
    pack(sh, "RN3", "33", 96.52, 152.4, ["B_CLK", "B_LATCH", "B_OE", "B_PL"],
         top=["OUT_CLK", "OUT_LATCH", "OUT_OE", "OUT_PL"])
    pack(sh, "RN4", "33", 127.0, 152.4, ["B_CLK165", "SR3", "Q165_LOCAL", None],
         top=["OUT_CLK165", "OUT_DATA", "Q165", None])

    # Shift registers
    regs = register_map()
    chain_in = {"U2": "B_DATA", "U3": "SR1", "U4": "SR2"}
    chain_out = {"U2": "SR1", "U3": "SR2", "U4": "SR3"}
    for ref, y in (("U2", 50.8), ("U3", 111.76), ("U4", 172.72)):
        u = sh.symbol("74xx:74HC595", ref, "74HC595", 200.66, y, footprint=FP_SOIC16)
        sh.connect(u, "14", chain_in[ref])
        sh.connect(u, "11", "B_CLK")
        sh.connect(u, "12", "B_LATCH")
        sh.connect(u, "13", "B_OE")
        sh.connect(u, "10", "+3V3")
        sh.connect(u, "16", "+3V3")
        sh.connect(u, "8", "GND")
        sh.connect(u, "9", chain_out[ref])
        for q in QPINS:
            sh.connect(u, q, regs[f"{ref}.{q}"])

    u5 = sh.symbol("74xx:74HC165", "U5", "74HC165", 200.66, 241.3, footprint=FP_SOIC16)
    for pin, n in input_map().items():
        sh.connect(u5, pin, n)
    sh.connect(u5, "10", "Q165_NEXT")
    sh.connect(u5, "1", "B_PL")
    sh.connect(u5, "2", "B_CLK165")
    sh.connect(u5, "15", "GND")
    sh.connect(u5, "9", "Q165_LOCAL")
    sh.no_connect(u5, "7")
    sh.connect(u5, "16", "+3V3")
    sh.connect(u5, "8", "GND")

    # Pull-ups on every drive line
    n = 10
    for d in range(1, 5):
        x = 243.84 + (d - 1) * 25.4
        pack(sh, f"RN{n}", "10k", x, 45.72, [net(d, s) for s in DRIVE_PULLUPS[:4]], rail="+3V3")
        pack(sh, f"RN{n + 1}", "10k", x, 83.82, [net(d, s) for s in DRIVE_PULLUPS[4:]], rail="+3V3")
        n += 2
    pack(sh, "RN18", "4.7k", 345.44, 45.72,
         [net(d, s) for d in (1, 2) for s in ("TRK0", "WP")], rail="+3V3")
    pack(sh, "RN19", "4.7k", 345.44, 83.82,
         [net(d, s) for d in (3, 4) for s in ("TRK0", "WP")], rail="+3V3")

    # Drive headers: J3 serves drives 1-2, J4 drives 3-4
    for ref, x, drives in (("J3", 271.78, (1, 2)), ("J4", 347.98, (3, 4))):
        j = sh.symbol("Connector_Generic:Conn_02x20_Odd_Even", ref, f"FDD{drives[0]}-{drives[1]}_IDE40",
                      x, 160.02, footprint=FP_IDE40)
        used = {}
        for slot, d in enumerate(drives):
            for sig, fp in FDD_PIN.items():
                used[ide_pin(slot, fp)] = net(d, sig)
            for gnd in range(11, 30, 2):
                used[ide_pin(slot, gnd)] = "GND"
        for p in range(1, 41):
            sh.connect(j, str(p), used[p])

    # Power: KF301 +5 V -> AMS1117-3.3
    mc.power_terminal(sh, "J5", 45.72, 203.2, ["+5V", "GND"])
    sh.text("J5 (KF301, 2 poles): pin 1 +5V (red), pin 2 GND (black). No +12 V on this connector.",
            (25.4, 218.44))
    u6 = sh.symbol("Regulator_Linear:AMS1117-3.3", "U6", "AMS1117-3.3", 104.14, 198.12,
                   footprint="Package_TO_SOT_SMD:SOT-223-3_TabPin2")
    sh.connect(u6, "3", "+5V")
    sh.connect(u6, "2", "+3V3")
    sh.connect(u6, "1", "GND")
    for ref, val, x, net_, fp in (("C6", "10u", 88.9, "+5V", FP_C), ("C7", "22u", 119.38, "+3V3", FP_C1206)):
        c = sh.symbol("Device:C", ref, val, x, 213.36, footprint=fp)
        sh.connect(c, "1", net_)
        sh.connect(c, "2", "GND")
    sh.flag("+5V", (63.5, 233.68))
    sh.flag("GND", (76.2, 241.3))

    # Decoupling, one per logic IC
    for i, x in enumerate((134.62, 144.78, 154.94, 165.1, 175.26)):
        c = sh.symbol("Device:C", f"C{i + 1}", "100n", x, 266.7, footprint=FP_C)
        sh.connect(c, "1", "+3V3")
        sh.connect(c, "2", "GND")
    sh.text("C1-C5: 100 nF next to U1-U5 supply pins.", (132.08, 281.94))

    for i in range(4):
        sh.symbol("Mechanical:MountingHole", f"H{i + 1}", "M3", 236.22 + i * 10.16, 279.4,
                  footprint=FP_HOLE)

    mc.diagnostics(sh, 292.1, 241.3, last="SR3")
    sh.save(path)


if __name__ == "__main__":
    build(sys.argv[1])
