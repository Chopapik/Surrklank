#!/usr/bin/env python3
"""Generate the remote panel schematic (buttons, LEDs, OLED, I2C expander).

Usage: python3 -I gen_panel.py <output.kicad_sch>
The cable pinout follows docs/WIRING.md (Remote panel) and mainboard J6.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from kicad_sch_lib import Sheet  # noqa: E402
import module_common as mc  # noqa: E402

FP_R = "Resistor_SMD:R_0805_2012Metric"
FP_C = "Capacitor_SMD:C_0805_2012Metric"
FP_IDC10 = "Connector_IDC:IDC-Header_2x05_P2.54mm_Vertical"
FP_SW = "Button_Switch_THT:SW_PUSH_6mm"
FP_LED = "LED_THT:LED_D3.0mm"
FP_SOCKET4 = "Connector_PinSocket_2.54mm:PinSocket_1x04_P2.54mm_Vertical"
# Expansion connectors: keyed JST-XH like the LSM/HDD motor outputs
FP_XH4 = "Connector_JST:JST_XH_B4B-XH-A_1x04_P2.50mm_Vertical"
FP_XH6 = "Connector_JST:JST_XH_B6B-XH-A_1x06_P2.50mm_Vertical"

# Cable from mainboard J6 (straight-through ribbon). Pin 1 is the ESP32 3V3.
CABLE = {1: "+3V3", 2: "GND", 3: "SDA", 4: "GND", 5: "SCL", 6: "GND",
         7: "INT", 8: "BUTTON", 9: "LED_SB", 10: "LED_ON"}
# Expander buttons (active LOW, MCP23017 internal pull-ups) and LEDs
BUTTONS = [("SW2", "PREV", "GPA0"), ("SW3", "PLAY", "GPA1"), ("SW4", "STOP", "GPA2"), ("SW5", "NEXT", "GPA3")]
EXP_LEDS = [("D3", "R1", "ATX_ON", "GPB0"), ("D4", "R2", "ESP_ACT", "GPB1")]
SPARE = ["GPA4", "GPA5", "GPA6", "GPA7"]          # spare button inputs on J2
UNUSED = ["GPB2", "GPB3", "GPB4", "GPB5", "GPB6", "GPB7"]


def build(path):
    sh = Sheet("surrklank-panel", "Surrklank remote panel", "0.1",
               comments=("Planned design, not built or tested. Wiring rules: docs/WIRING.md",
                         "Generated by hardware/tools/gen_panel.py - do not edit by hand"))

    j1 = sh.symbol("Connector_Generic:Conn_02x05_Odd_Even", "J1", "MAINBOARD", 38.1, 76.2, footprint=FP_IDC10)
    for p, n in CABLE.items():
        sh.connect(j1, str(p), n)
    sh.flag("+3V3", (25.4, 50.8))
    sh.flag("GND", (38.1, 50.8))
    sh.text("J1: cable to mainboard J6 (2 x 5, straight-through, up to about 2 m).\n"
            "+3V3 is the ESP32 board's 3.3 V. I2C pull-ups are on the mainboard.", (20.32, 101.6))

    # Hardware status LEDs: anode feed resistors are on the mainboard
    for ref, net, label in (("D1", "LED_SB", "STANDBY"), ("D2", "LED_ON", "RAILS")):
        d = sh.symbol("Device:LED", ref, label, 76.2 if ref == "D1" else 91.44, 76.2, angle=90, footprint=FP_LED)
        sh.connect(d, "name:A", net)
        sh.connect(d, "name:K", "GND")
    sh.text("D1: +5VSB present, D2: ATX main rails up (no firmware).\n"
            "Use LEDs with Vf about 2 V (red, green, yellow).", (68.58, 96.52))

    sw1 = sh.symbol("Switch:SW_Push", "SW1", "POWER", 76.2, 121.92, footprint=FP_SW)
    sh.connect(sw1, "1", "BUTTON")
    sh.connect(sw1, "2", "GND")
    sh.text("SW1: ATX button, wired straight to GPIO13 (works without I2C).", (63.5, 132.08))

    # I2C expander, address 0x20 (A2..A0 = GND)
    u1 = sh.symbol("Interface_Expansion:MCP23017x-x-SO", "U1", "MCP23017-E/SO", 175.26, 88.9,
                   footprint="Package_SO:SOIC-28W_7.5x17.9mm_P1.27mm")
    sh.connect(u1, "name:V_{DD}", "+3V3")
    sh.connect(u1, "name:V_{SS}", "GND")
    sh.connect(u1, "name:SCK", "SCL")
    sh.connect(u1, "name:SDA", "SDA")
    sh.connect(u1, "name:INTA", "INT")
    sh.no_connect(u1, "name:INTB")
    for a in ("A0", "A1", "A2"):
        sh.connect(u1, f"name:{a}", "GND")
    sh.connect(u1, "name:~{RESET}", "EXP_RST")
    for pin in ("11", "14"):
        sh.no_connect(u1, pin)
    for _, _, gp in BUTTONS:
        sh.connect(u1, f"name:{gp}", f"BTN_{gp}")
    for _, _, net, gp in EXP_LEDS:
        sh.connect(u1, f"name:{gp}", f"LEDDRV_{net}")
    for gp in SPARE:
        sh.connect(u1, f"name:{gp}", f"EXP_{gp}")
    for gp in UNUSED:
        sh.no_connect(u1, f"name:{gp}")
    r3 = sh.symbol("Device:R", "R3", "10k", 147.32, 60.96, footprint=FP_R)
    sh.connect(r3, "1", "+3V3")
    sh.connect(r3, "2", "EXP_RST")
    for ref, val, x in (("C1", "100n", 147.32), ("C2", "10u", 157.48)):
        c = sh.symbol("Device:C", ref, val, x, 129.54, footprint=FP_C)
        sh.connect(c, "1", "+3V3")
        sh.connect(c, "2", "GND")
    sh.text("U1 MCP23017 at I2C address 0x20. INTA mirrors both ports (IOCON.MIRROR);\n"
            "buttons use the internal pull-ups (GPPU). C1 next to VDD.", (149.86, 144.78))

    for i, (ref, label, gp) in enumerate(BUTTONS):
        sw = sh.symbol("Switch:SW_Push", ref, label, 246.38, 60.96 + i * 12.7, footprint=FP_SW)
        sh.connect(sw, "1", f"BTN_{gp}")
        sh.connect(sw, "2", "GND")
    for i, (dref, rref, net, gp) in enumerate(EXP_LEDS):
        y = 129.54 + i * 15.24
        r = sh.symbol("Device:R", rref, "330", 233.68, y, angle=90, footprint=FP_R)
        sh.connect(r, "1", f"LEDDRV_{net}")
        sh.connect(r, "2", f"LED_{net}")
        d = sh.symbol("Device:LED", dref, net, 254.0, y, angle=180, footprint=FP_LED)
        sh.connect(d, "name:A", f"LED_{net}")
        sh.connect(d, "name:K", "GND")
    sh.text("D3: ATX ON request (GPIO19 state), D4: ESP32 activity; firmware-driven.", (220.98, 160.02))

    # OLED module socket and expansion headers
    oled = sh.symbol("Connector_Generic:Conn_01x04", "J4", "OLED_SSD1306", 38.1, 152.4, footprint=FP_SOCKET4)
    for p, n in zip("1234", ("GND", "+3V3", "SCL", "SDA")):
        sh.connect(oled, p, n)
    sh.text("J4: 0.96 inch SSD1306 OLED module (I2C 0x3C), pin order GND VCC SCL SDA.\n"
            "Check the module's pin labels: some modules swap GND and VCC.", (20.32, 167.64))
    j3 = sh.symbol("Connector_Generic:Conn_01x04", "J3", "I2C_EXT", 106.68, 152.4, footprint=FP_XH4)
    for p, n in zip("1234", ("GND", "+3V3", "SCL", "SDA")):
        sh.connect(j3, p, n)
    j2 = sh.symbol("Connector_Generic:Conn_01x06", "J2", "EXP_SPARE", 307.34, 88.9, footprint=FP_XH6)
    for p, n in zip(range(1, 7), ["+3V3", "GND"] + [f"EXP_{g}" for g in SPARE]):
        sh.connect(j2, str(p), n)
    sh.text("J2: GPA4-GPA6 for buttons (to GND); GPA7 is output only. GPB2-GPB7 unused.\n"
            "J3: more I2C devices (another MCP23017 needs a different address).", (281.94, 124.46))

    mc.mounting_holes(sh, 236.22, 279.4)
    sh.save(path)


if __name__ == "__main__":
    build(sys.argv[1])
