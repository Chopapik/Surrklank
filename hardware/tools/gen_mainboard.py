#!/usr/bin/env python3
"""Generate the mainboard schematic (ESP32 board, ATX, two ribbon branches).

Usage: python3 -I gen_mainboard.py <output.kicad_sch>
GPIO assignment and default levels follow docs/WIRING.md (Mainboard).
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from kicad_sch_lib import Sheet  # noqa: E402
import module_common as mc  # noqa: E402

FP_R = "Resistor_SMD:R_0805_2012Metric"
FP_C = "Capacitor_SMD:C_0805_2012Metric"
FP_TERM = "surrklank:TerminalBlock_KF301_1x05_P5.08mm_Horizontal"
FP_JST2 = "Connector_JST:JST_XH_B2B-XH-A_1x02_P2.50mm_Vertical"
FP_JUMPER = "Connector_PinHeader_2.54mm:PinHeader_1x02_P2.54mm_Vertical"
FP_IDC10 = "Connector_IDC:IDC-Header_2x05_P2.54mm_Vertical"

# ESP32 board pin -> net (pin numbers of surrklank:ESP32_DevKitC_38); others not connected
ESP = {"1": "ESP_3V3", "3": "PWR_OK_IN", "5": "FDD_Q165", "6": "ACT_Q165", "7": "CLK165",
       "8": "PL", "9": "PANEL_SDA", "10": "PANEL_SCL", "11": "PANEL_INT", "14": "GND", "15": "BUTTON", "19": "ESP_5V",
       "20": "GND", "21": "FDD_DATA", "22": "FDD_LATCH", "25": "OE", "26": "GND",
       "27": "ATX_EN", "28": "CLK", "30": "ACT_DATA", "31": "ACT_LATCH"}
# Remote panel cable (2 x 5 IDC): I2C with a GND between SDA and SCL
PANEL = {1: "ESP_3V3", 2: "GND", 3: "PANEL_SDA", 4: "GND", 5: "PANEL_SCL", 6: "GND",
         7: "PANEL_INT", 8: "BUTTON", 9: "PANEL_LED_SB", 10: "PANEL_LED_ON"}
RIBBON = {1: "DATA", 3: "CLK", 5: "LATCH", 7: "OE", 9: "PL", 11: "CLK165", 13: "Q165", 15: "SPARE"}


def label_flag(sh, net, p):
    """PWR_FLAG on a labelled net (no power symbol exists for it)."""
    sh.symbol("power:PWR_FLAG", f"#FLG{len(sh.items):03d}", "PWR_FLAG", p[0], p[1], 0)
    q = (p[0], round(p[1] + 5.08, 4))
    sh.wire(p, q)
    sh.label(net, q, (0, 1))


def resistor(sh, ref, value, x, y, a, b):
    r = sh.symbol("Device:R", ref, value, x, y, footprint=FP_R)
    sh.connect(r, "1", a)
    sh.connect(r, "2", b)


def build(path):
    sh = Sheet("surrklank-mainboard", "Surrklank mainboard (ESP32, ATX, two branches)", "0.1",
               comments=("Planned design, not built or tested. Wiring rules: docs/WIRING.md",
                         "Generated by hardware/tools/gen_mainboard.py - do not edit by hand"))

    esp = sh.symbol("surrklank:ESP32_DevKitC_38", "A1", "ESP32_DevKitC_38", 76.2, 101.6,
                    footprint="surrklank:ESP32_DevKitC_38_W24.85mm")
    for pin in range(1, 39):
        n = ESP.get(str(pin))
        if n is None:
            sh.no_connect(esp, str(pin))
        else:
            sh.connect(esp, str(pin), n)
    sh.text("A1 pins 1/20 at the antenna end. ESP32 3V3 is the board's own regulator:\n"
            "never connect ATX +5V to it. Mainboard pull resistors use ESP_3V3.",
            (50.8, 63.5))

    # Default levels on the GPIO side (ESP32 boot / high impedance)
    mc.pack(sh, "RN1", "10k", 127.0, 50.8, ["OE", "PL", "BUTTON", "PANEL_INT"], rail="ESP_3V3")
    mc.pack(sh, "RN2", "10k", 142.24, 50.8, ["CLK", "CLK165", "FDD_LATCH", "ACT_LATCH"], rail="GND")
    mc.pack(sh, "RN3", "10k", 157.48, 50.8, ["FDD_DATA", "ACT_DATA", "FDD_Q165", "ACT_Q165"], rail="GND")

    # Two ribbon branches with series resistors on every output
    for k, (pre, name, ref, y) in enumerate((("F", "FDD", "J2", 101.6), ("A", "ACT", "J3", 177.8))):
        rna, rnb = f"RN{4 + 2 * k}", f"RN{5 + 2 * k}"
        mc.pack(sh, rna, "33", 132.08, y - 12.7, ["CLK", "OE", "PL", "CLK165"],
                top=[f"{pre}_CLK", f"{pre}_OE", f"{pre}_PL", f"{pre}_CLK165"])
        mc.pack(sh, rnb, "33", 152.4, y - 12.7, [f"{name}_DATA", f"{name}_LATCH", None, None],
                top=[f"{pre}_DATA", f"{pre}_LATCH", None, None])
        j = sh.symbol("Connector_Generic:Conn_02x08_Odd_Even", ref, f"RIBBON_{name}", 203.2, y,
                      footprint=mc.FP_IDC16)
        for p in range(1, 17):
            if p % 2 == 0:
                sh.connect(j, str(p), "GND")
            elif RIBBON[p] == "Q165":
                sh.connect(j, str(p), f"{pre}_Q165")
            elif RIBBON[p] == "SPARE":
                sh.no_connect(j, str(p))   # spare wire, passes through the modules
            else:
                sh.connect(j, str(p), f"{pre}_{RIBBON[p]}")
        # Q165 return: 1k limits current if a powered module drives an unpowered ESP32
        resistor(sh, f"R{5 + k}", "1k", 172.72, y - 12.7, f"{pre}_Q165", f"{name}_Q165")
    sh.text("J2: FDD branch, J3: actuator branch (same 16-pin ribbon).\n"
            "Pin 15 is a spare wire; no power runs on the ribbons.", (190.5, 66.04))

    # ATX power terminal
    j1 = sh.symbol("Connector:Screw_Terminal_01x05", "J1", "ATX_IN", 38.1, 190.5, footprint=FP_TERM)
    for pin, n in zip("12345", ["+5V", "GND", "PS_ON#", "ATX_5VSB", "PWR_OK"]):
        sh.connect(j1, pin, n)
    sh.text("J1: KF301 screw terminal from the ATX 24-pin distribution:\n"
            "1 +5V (red), 2 GND, 3 PS_ON# (green), 4 +5VSB (purple), 5 PWR_OK (grey).",
            (20.32, 213.36))
    sh.flag("+5V", (25.4, 233.68))
    sh.flag("GND", (38.1, 241.3))
    label_flag(sh, "ATX_5VSB", (50.8, 233.68))

    # +5VSB -> removable jumper -> ESP32 5 V pin (no diode: full 5 V for the
    # ESP32 board's regulator; JP1 is the only isolation from USB)
    jp1 = sh.symbol("Jumper:Jumper_2_Open", "JP1", "5VSB_EN", 134.62, 190.5, footprint=FP_JUMPER)
    sh.connect(jp1, "1", "ATX_5VSB")
    sh.connect(jp1, "2", "ESP_5V")
    c1 = sh.symbol("Device:C", "C1", "10u", 147.32, 198.12, footprint=FP_C)
    sh.connect(c1, "1", "ESP_5V")
    sh.connect(c1, "2", "GND")
    label_flag(sh, "ESP_5V", (160.02, 185.42))
    sh.text("Remove JP1 BEFORE plugging in USB: it is the only thing\n"
            "keeping USB 5 V out of the ATX standby rail (and +5VSB out of USB).", (93.98, 205.74))
    c2 = sh.symbol("Device:C", "C2", "100n", 172.72, 198.12, footprint=FP_C)
    sh.connect(c2, "1", "ESP_3V3")
    sh.connect(c2, "2", "GND")

    # PWR_OK (5 V logic) -> divider -> GPIO36
    resistor(sh, "R1", "10k", 101.6, 233.68, "PWR_OK", "PWR_OK_IN")
    resistor(sh, "R2", "20k", 116.84, 233.68, "PWR_OK_IN", "GND")

    # ATX PS_ON# switch
    q1 = sh.symbol("Transistor_BJT:MMBT3904", "Q1", "MMBT3904", 167.64, 233.68,
                   footprint="Package_TO_SOT_SMD:SOT-23")
    sh.connect(q1, "name:B", "Q1_B")
    sh.connect(q1, "name:E", "GND")
    sh.connect(q1, "name:C", "PS_ON#")
    resistor(sh, "R3", "2.2k", 142.24, 233.68, "ATX_EN", "Q1_B")
    resistor(sh, "R4", "100k", 152.4, 233.68, "Q1_B", "GND")

    j4 = sh.symbol("Connector_Generic:Conn_01x02", "J4", "ATX_BUTTON", 210.82, 233.68, footprint=FP_JST2)
    sh.connect(j4, "1", "BUTTON")
    sh.connect(j4, "2", "GND")
    c3 = sh.symbol("Device:C", "C3", "100n", 223.52, 233.68, footprint=FP_C)
    sh.connect(c3, "1", "BUTTON")
    sh.connect(c3, "2", "GND")
    sh.text("J4: normally-open button to GND. RN1 10k pull-up to ESP_3V3 and C3\n"
            "filter noise picked up by the button cable near the motors.", (195.58, 246.38))

    # Remote panel: I2C (OLED, I/O expander), expander INT, ATX button in
    # parallel with J4, and two hardware status LEDs (LEDs sit on the panel).
    j6 = sh.symbol("Connector_Generic:Conn_02x05_Odd_Even", "J6", "PANEL", 320.04, 101.6,
                   footprint=FP_IDC10)
    for p, n in PANEL.items():
        sh.connect(j6, str(p), n)
    resistor(sh, "R7", "2.2k", 279.4, 81.28, "PANEL_SDA", "ESP_3V3")
    resistor(sh, "R8", "2.2k", 289.56, 81.28, "PANEL_SCL", "ESP_3V3")
    resistor(sh, "R9", "1k", 279.4, 127.0, "ATX_5VSB", "PANEL_LED_SB")
    resistor(sh, "R10", "470", 289.56, 127.0, "+5V", "PANEL_LED_ON")
    sh.text("J6: remote panel, cable up to about 2 m. I2C at 100 kHz with 2.2k\n"
            "pull-ups (GPIO25 SDA, GPIO26 SCL); GPIO27 = expander INT (RN1 pull-up).\n"
            "Pin 9: LED anode via R9 from +5VSB (standby present).\n"
            "Pin 10: LED anode via R10 from ATX +5V (main rails up).\n"
            "Panel LEDs to GND; use red/green/yellow (Vf about 2 V).", (264.16, 147.32))

    mc.mounting_holes(sh, 236.22, 279.4)
    sh.save(path)


if __name__ == "__main__":
    build(sys.argv[1])
