#!/usr/bin/env python3
"""Generate the mainboard schematic (ESP32 board, ATX, two ribbon branches).

Usage: python3 -I gen_mainboard.py <output.kicad_sch>
GPIO assignment and default levels follow docs/WIRING.md (Mainboard).
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from kicad_sch_lib import Sheet  # noqa: E402
import module_common as mc  # noqa: E402

FP_R = "Resistor_SMD:R_0805_2012Metric"
FP_C = "Capacitor_SMD:C_0805_2012Metric"
FP_TERM = "Connector_Phoenix_MSTB:PhoenixContact_MSTBA_2,5_5-G-5,08_1x05_P5.08mm_Horizontal"
FP_JST2 = "Connector_JST:JST_XH_B2B-XH-A_1x02_P2.50mm_Vertical"
FP_JUMPER = "Connector_PinHeader_2.54mm:PinHeader_1x02_P2.54mm_Vertical"

# ESP32 board pin -> net (pin numbers of surrklank:ESP32_DevKitC_38); others not connected
ESP = {"1": "ESP_3V3", "3": "PWR_OK_IN", "5": "FDD_Q165", "6": "LSM_Q165", "7": "CLK165",
       "8": "PL", "14": "GND", "15": "BUTTON", "19": "ESP_5V",
       "20": "GND", "21": "FDD_DATA", "22": "FDD_LATCH", "25": "OE", "26": "GND",
       "27": "ATX_EN", "28": "CLK", "30": "LSM_DATA", "31": "LSM_LATCH"}
RIBBON = {1: "DATA", 3: "CLK", 5: "LATCH", 7: "OE", 9: "PL", 11: "CLK165", 13: "Q165", 15: "3V3"}


def label_flag(sh, net, p):
    """PWR_FLAG on a labelled net (no power symbol exists for it)."""
    sh.symbol("power:PWR_FLAG", f"#FLG{len(sh.items):03d}", "PWR_FLAG", p[0], p[1], 0)
    q = (p[0], round(p[1] + 5.08, 4))
    sh.wire(p, q)
    sh.label(net, q, (0, 1))


def resistor(sh, ref, value, x, y, a, b):
    r = sh.symbol("Device:R", ref, value, x, y, footprint=FP_R)
    sh.connect(r, "1", a)
    sh.connect(r, "2", b)


def build(path):
    sh = Sheet("surrklank-mainboard", "Surrklank mainboard (ESP32, ATX, two branches)", "0.1",
               comments=("Planned design, not built or tested. Wiring rules: docs/WIRING.md",
                         "Generated by hardware/tools/gen_mainboard.py - do not edit by hand"))

    esp = sh.symbol("surrklank:ESP32_DevKitC_38", "A1", "ESP32_DevKitC_38", 76.2, 101.6,
                    footprint="surrklank:ESP32_DevKitC_38_W25.4mm")
    for pin in range(1, 39):
        n = ESP.get(str(pin))
        if n is None:
            sh.no_connect(esp, str(pin))
        else:
            sh.connect(esp, str(pin), n)
    sh.text("A1 pins 1/20 at the antenna end. ESP32 3V3 is the board's own regulator:\n"
            "never connect ATX +3V3 to it. Mainboard pull resistors use ESP_3V3.",
            (50.8, 63.5))

    # Default levels on the GPIO side (ESP32 boot / high impedance)
    mc.pack(sh, "RN1", "10k", 127.0, 50.8, ["OE", "PL", None, None], rail="ESP_3V3")
    mc.pack(sh, "RN2", "10k", 142.24, 50.8, ["CLK", "CLK165", "FDD_LATCH", "LSM_LATCH"], rail="GND")
    mc.pack(sh, "RN3", "10k", 157.48, 50.8, ["FDD_DATA", "LSM_DATA", "FDD_Q165", "LSM_Q165"], rail="GND")

    # Two ribbon branches with series resistors on every output
    for k, (pre, name, ref, y) in enumerate((("F", "FDD", "J2", 101.6), ("L", "LSM", "J3", 177.8))):
        rna, rnb = f"RN{4 + 2 * k}", f"RN{5 + 2 * k}"
        mc.pack(sh, rna, "33", 132.08, y - 12.7, ["CLK", "OE", "PL", "CLK165"],
                top=[f"{pre}_CLK", f"{pre}_OE", f"{pre}_PL", f"{pre}_CLK165"])
        mc.pack(sh, rnb, "33", 152.4, y - 12.7, [f"{name}_DATA", f"{name}_LATCH", None, None],
                top=[f"{pre}_DATA", f"{pre}_LATCH", None, None])
        j = sh.symbol("Connector_Generic:Conn_02x08_Odd_Even", ref, f"RIBBON_{name}", 203.2, y,
                      footprint=mc.FP_IDC16)
        for p in range(1, 17):
            if p % 2 == 0:
                sh.connect(j, str(p), "GND")
            elif RIBBON[p] == "Q165":
                sh.connect(j, str(p), f"{name}_Q165")
            elif RIBBON[p] == "3V3":
                sh.connect(j, str(p), f"{pre}_RIB3V3")
            else:
                sh.connect(j, str(p), f"{pre}_{RIBBON[p]}")
        jp = sh.symbol("Jumper:SolderJumper_2_Open", f"JP{2 + k}", "BENCH_3V3", 241.3, y + 10.16,
                       footprint=mc.FP_JP)
        sh.connect(jp, "1", f"{pre}_RIB3V3")
        sh.connect(jp, "2", "+3V3")
    sh.text("J2: FDD branch, J3: LSM/HDD branch (same 16-pin ribbon).\n"
            "JP2/JP3: close only to power one module from ATX +3V3 on the bench.", (190.5, 66.04))

    # ATX power terminal
    j1 = sh.symbol("Connector:Screw_Terminal_01x05", "J1", "ATX_IN", 38.1, 190.5, footprint=FP_TERM)
    for pin, n in zip("12345", ["+3V3", "GND", "PS_ON#", "ATX_5VSB", "PWR_OK"]):
        sh.connect(j1, pin, n)
    sh.text("J1: pluggable terminal from the ATX 24-pin distribution:\n"
            "1 +3V3 (orange), 2 GND, 3 PS_ON# (green), 4 +5VSB (purple), 5 PWR_OK (grey).",
            (20.32, 213.36))
    sh.flag("+3V3", (25.4, 233.68))
    sh.flag("GND", (38.1, 241.3))
    label_flag(sh, "ATX_5VSB", (50.8, 233.68))

    # +5VSB -> Schottky -> removable jumper -> ESP32 5 V pin
    d1 = sh.symbol("Diode:SS34", "D1", "SS34", 101.6, 190.5, angle=180, footprint="Diode_SMD:D_SMA")
    sh.connect(d1, "2", "ATX_5VSB")   # anode
    sh.connect(d1, "1", "5VSB_D")     # cathode
    jp1 = sh.symbol("Jumper:Jumper_2_Open", "JP1", "5VSB_EN", 134.62, 190.5, footprint=FP_JUMPER)
    sh.connect(jp1, "1", "5VSB_D")
    sh.connect(jp1, "2", "ESP_5V")
    c1 = sh.symbol("Device:C", "C1", "10u", 147.32, 198.12, footprint=FP_C)
    sh.connect(c1, "1", "ESP_5V")
    sh.connect(c1, "2", "GND")
    label_flag(sh, "ESP_5V", (160.02, 185.42))
    sh.text("JP1 removed = ESP32 isolated from ATX for USB flashing.\n"
            "D1 keeps USB 5 V out of the ATX standby rail.", (93.98, 205.74))
    c2 = sh.symbol("Device:C", "C2", "100n", 172.72, 198.12, footprint=FP_C)
    sh.connect(c2, "1", "ESP_3V3")
    sh.connect(c2, "2", "GND")

    # PWR_OK (5 V logic) -> divider -> GPIO36
    resistor(sh, "R1", "10k", 101.6, 233.68, "PWR_OK", "PWR_OK_IN")
    resistor(sh, "R2", "20k", 116.84, 233.68, "PWR_OK_IN", "GND")

    # ATX PS_ON# switch
    q1 = sh.symbol("Transistor_BJT:MMBT3904", "Q1", "MMBT3904", 167.64, 233.68,
                   footprint="Package_TO_SOT_SMD:SOT-23")
    sh.connect(q1, "name:B", "Q1_B")
    sh.connect(q1, "name:E", "GND")
    sh.connect(q1, "name:C", "PS_ON#")
    resistor(sh, "R3", "2.2k", 142.24, 233.68, "ATX_EN", "Q1_B")
    resistor(sh, "R4", "100k", 152.4, 233.68, "Q1_B", "GND")

    j4 = sh.symbol("Connector_Generic:Conn_01x02", "J4", "ATX_BUTTON", 210.82, 233.68, footprint=FP_JST2)
    sh.connect(j4, "1", "BUTTON")
    sh.connect(j4, "2", "GND")
    sh.text("J4: normally-open button to GND (GPIO13 internal pull-up).", (195.58, 246.38))

    mc.mounting_holes(sh, 236.22, 279.4)
    sh.save(path)


if __name__ == "__main__":
    build(sys.argv[1])
